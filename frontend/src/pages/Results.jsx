import React, { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { useInspection } from "../context/InspectionContext.jsx";
import { assetUrl, downloadAsset, getInspection } from "../api/client.js";

function buildReportText(r) {
  const isReal = r.classifier_used === "random_forest_trained";
  const lines = [
    "STEEL SURFACE DEFECT CLASSIFICATION",
    "DIGITAL IMAGE PROCESSING INSPECTION REPORT",
    "=".repeat(64),
    `Inspection ID:         ${r.id ?? "N/A"}`,
    `Timestamp:              ${r.timestamp}`,
    `Original filename:      ${r.original_filename}`,
    `Mode:                   ${r.model_mode}`,
    "",
    "MODEL PREDICTION",
    "-".repeat(64),
    `Result:                 ${r.result}`,
    `Predicted class:        ${r.predicted_class ?? "N/A"}`,
    isReal
      ? `Model probability:      ${r.model_probability != null ? (r.model_probability * 100).toFixed(1) + "%" : "N/A"} (real predict_proba output, not calibrated confidence)`
      : `Heuristic score:        ${r.heuristic_score ?? "N/A"} (rule-based demo weight, not a probability)`,
    `Defect candidate regions: ${r.num_regions}`,
    `Candidate region area:  ${r.defect_area_percent ?? 0}%`,
    `Classifier:             ${r.classifier_used}`,
    isReal ? `Model version:          ${r.model_version ?? "N/A"}` : null,
    `Processing time:        ${r.processing_time_ms} ms`,
    "",
    "DIP TECHNIQUES USED",
    "-".repeat(64),
    ...r.stages.map((s) => `${s.step}. ${s.title}: ${s.technique}`),
    "",
    "EXTRACTED FEATURE SUMMARY",
    "-".repeat(64),
    ...(r.features ? Object.entries(r.features).map(([k, v]) => `${k}: ${v}`) : ["N/A"]),
    "",
    "METHODOLOGY (SHORT)",
    "-".repeat(64),
    "Image preprocessed (resize/normalize, grayscale, median denoise, CLAHE contrast",
    "enhancement), edge-detected (Canny), segmented (Otsu + edge agreement), cleaned",
    "(morphological opening/closing/hole-filling), analyzed for connected components,",
    "and described with a 23-value feature vector (global texture + regional geometry).",
    isReal
      ? "That vector was scaled with the training-set StandardScaler and classified by a"
      : "Because this run used Demo Mode, that vector was classified by a transparent",
    isReal
      ? "RandomForestClassifier trained on the real NEU-CLS steel surface defect dataset."
      : "rule-based heuristic rather than a trained model.",
    "",
    "LIMITATIONS",
    "-".repeat(64),
    isReal
      ? "This model is trained and validated only on NEU-CLS (6 known steel-surface defect"
      : "This is a rule-based demo heuristic, tuned only against synthetic images, not a"
    ,
    isReal
      ? "categories; there is no 'no defect' class in that dataset). Predictions on unrelated"
      : "validated model. See the Methodology page for the full limitations discussion."
    ,
    isReal ? "images are not meaningful. See /api/model/info for real held-out test metrics." : null,
    "",
    "NOTE ON CANDIDATE REGIONS",
    "-".repeat(64),
    r.candidate_regions_disclaimer ||
      "Candidate regions are generated by the Digital Image Processing pipeline. The NEU-CLS " +
      "dataset does not provide ground-truth segmentation masks, so these regions should not be " +
      "interpreted as verified defect boundaries.",
  ].filter((l) => l !== null);
  return lines.join("\n");
}

function downloadText(filename, text) {
  const blob = new Blob([text], { type: "text/plain" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export default function Results() {
  const { id } = useParams();
  const { currentResult, setCurrentResult } = useInspection();
  const [loaded, setLoaded] = useState(currentResult);
  const [loading, setLoading] = useState(false);
  const [err, setErr] = useState(null);
  const [downloadError, setDownloadError] = useState(null);

  useEffect(() => {
    if (id) {
      setLoading(true);
      getInspection(id)
        .then((r) => { setLoaded(r); setCurrentResult(r); })
        .catch((e) => setErr(e.message))
        .finally(() => setLoading(false));
    } else {
      setLoaded(currentResult);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [id]);

  if (loading) {
    return <div className="max-w-4xl mx-auto px-5 py-20 text-center text-slate-400">Loading inspection…</div>;
  }

  if (err || !loaded) {
    return (
      <div className="max-w-3xl mx-auto px-5 py-20 text-center">
        <h1 className="text-2xl font-semibold">No result to show</h1>
        <p className="text-slate-400 mt-2">{err || "Run an inspection first."}</p>
        <Link to="/inspection" className="inline-block mt-6 px-5 py-2.5 rounded-md bg-accent-500 hover:bg-accent-600 text-white font-semibold">
          Start Inspection
        </Link>
      </div>
    );
  }

  const r = loaded;
  const isReal = r.classifier_used === "random_forest_trained";
  const isPositive = r.result === "DEFECT_DETECTED" || r.result === "CLASSIFIED";

  return (
    <div className="max-w-6xl mx-auto px-5 py-12">
      <div className="flex items-center gap-2 mb-3">
        <span className="label-chip border-ink-600 text-slate-400">STEP 3</span>
        <span className={`label-chip ${isReal ? "border-ok-500/40 text-ok-500 bg-ok-500/10" : "border-ink-600 text-slate-400"}`}>
          {r.model_mode}
        </span>
      </div>
      <h1 className="text-3xl font-bold mb-8">Inspection Result</h1>

      <div className="grid lg:grid-cols-2 gap-8">
        <div className="space-y-4">
          <div className="card p-3">
            <div className="text-xs uppercase tracking-wider text-slate-500 px-2 pt-1 pb-2">Original</div>
            <img src={assetUrl(r.original_image_url)} alt="original" className="w-full rounded-md" />
          </div>
        </div>
        <div className="space-y-4">
          <div className={`card p-3 border-2 ${isPositive ? "border-warn-500/50" : "border-ok-500/50"}`}>
            <div className="text-xs uppercase tracking-wider text-slate-500 px-2 pt-1 pb-2">Candidate Defect Regions (DIP Segmentation)</div>
            <img src={assetUrl(r.highlighted_image_url)} alt="highlighted" className="w-full rounded-md" />
          </div>
        </div>
      </div>

      <div className="mt-4 px-4 py-2.5 rounded-md bg-ink-700/50 border border-ink-600 text-xs text-slate-400">
        {r.candidate_regions_disclaimer || "Candidate regions are generated by the Digital Image Processing pipeline. The NEU-CLS dataset does not provide ground-truth segmentation masks, so these regions should not be interpreted as verified defect boundaries."}
      </div>

      <div className={`mt-8 card p-6 border-2 ${isPositive ? "border-warn-500/50" : "border-ok-500/50"}`}>
        <div className="flex items-center gap-3">
          <span className={`w-3 h-3 rounded-full ${isPositive ? "bg-warn-500" : "bg-ok-500"}`} />
          <div className={`text-2xl font-bold ${isPositive ? "text-warn-500" : "text-ok-500"}`}>
            {r.result === "CLASSIFIED" ? `Predicted Class: ${r.predicted_class}` :
             r.result === "DEFECT_DETECTED" ? "DEFECT DETECTED" : "NO DEFECT DETECTED"}
          </div>
        </div>

        <div className="grid sm:grid-cols-2 md:grid-cols-4 gap-4 mt-6">
          <Stat label="Predicted Class" value={r.predicted_class || "N/A"} />
          <Stat label="Candidate Regions" value={r.num_regions} />
          <Stat label="Processing Time" value={`${r.processing_time_ms} ms`} />
          {isReal ? (
            <Stat label="Model Probability" value={r.model_probability != null ? `${(r.model_probability * 100).toFixed(1)}%` : "N/A"} />
          ) : (
            <Stat label="Heuristic Score" value={r.heuristic_score ?? "N/A"} />
          )}
        </div>

        {isReal && r.per_class_probability && (
          <div className="mt-5">
            <div className="text-xs uppercase tracking-wider text-slate-500 mb-2">Per-Class Probability (real predict_proba)</div>
            <div className="space-y-1.5">
              {Object.entries(r.per_class_probability).sort((a, b) => b[1] - a[1]).map(([cls, p]) => (
                <div key={cls} className="flex items-center gap-2">
                  <div className="w-32 text-xs font-mono text-slate-400 truncate">{cls}</div>
                  <div className="flex-1 h-2 rounded-sm bg-ink-700 overflow-hidden">
                    <div className="h-full bg-accent-500" style={{ width: `${p * 100}%` }} />
                  </div>
                  <div className="w-12 text-xs font-mono text-right">{(p * 100).toFixed(1)}%</div>
                </div>
              ))}
            </div>
          </div>
        )}

        <div className="mt-4 text-xs font-mono text-slate-500">
          {isReal
            ? `Trained RandomForestClassifier${r.model_version ? ` v${r.model_version}` : ""}. Probability is the model's predict_proba() output, not calibrated confidence.`
            : "Rule-based demo classifier. The heuristic score is not a probability or trained-model output."}
        </div>

        <div className="flex gap-3 mt-6 flex-wrap">
          <button
            type="button"
            onClick={() => {
              setDownloadError(null);
              downloadAsset(assetUrl(r.highlighted_image_url), `inspection_${r.id ?? "result"}.png`)
                .catch((e) => setDownloadError(e.message));
            }}
            className="px-4 py-2 rounded-md border border-ink-600 hover:border-ink-500 text-sm font-medium"
          >
            Download Result Image
          </button>
          <button
            onClick={() => downloadText(`inspection_${r.id ?? "report"}.txt`, buildReportText(r))}
            className="px-4 py-2 rounded-md border border-ink-600 hover:border-ink-500 text-sm font-medium"
          >
            Download Inspection Report
          </button>
          <Link to="/pipeline" className="px-4 py-2 rounded-md border border-ink-600 hover:border-ink-500 text-sm font-medium">
            Review Pipeline Stages
          </Link>
        </div>
        {downloadError && <div role="alert" className="mt-3 text-sm text-warn-500">{downloadError}</div>}
      </div>
    </div>
  );
}

function Stat({ label, value }) {
  return (
    <div className="card px-4 py-3">
      <div className="text-[10px] uppercase tracking-wider text-slate-500">{label}</div>
      <div className="text-lg font-semibold font-mono mt-0.5">{value}</div>
    </div>
  );
}
