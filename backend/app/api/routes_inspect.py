import datetime
import json
import uuid
from pathlib import Path

from fastapi import APIRouter, Depends, UploadFile, File, Form, HTTPException
from sqlalchemy.orm import Session

from app import models, schemas
from app.config import UPLOAD_DIR, ALLOWED_EXTENSIONS
from app.database import get_db
from app.pipeline.pipeline_runner import run_pipeline
from app.pipeline.classifier import ModelNotAvailableError, FeatureContractError
from app.api.upload_utils import read_upload_limited

router = APIRouter(prefix="/api", tags=["inspection"])


CANDIDATE_REGIONS_DISCLAIMER = (
    "Candidate regions are generated by the Digital Image Processing pipeline. The NEU-CLS "
    "dataset does not provide ground-truth segmentation masks, so these regions should not be "
    "interpreted as verified defect boundaries."
)


def _record_to_response(record: models.Inspection) -> schemas.InspectionResponse:
    return schemas.InspectionResponse(
        id=record.id,
        timestamp=_as_utc(record.timestamp),
        original_filename=record.original_filename,
        mode=record.mode,
        model_mode=record.model_mode,
        result=record.result,
        predicted_class=record.predicted_class,
        num_regions=record.num_regions,
        defect_area_percent=record.defect_area_percent,
        candidate_regions_disclaimer=CANDIDATE_REGIONS_DISCLAIMER,
        classifier_used=record.classifier_used,
        model_probability=record.model_probability,
        heuristic_score=record.heuristic_score,
        per_class_probability=json.loads(record.per_class_probability_json) if record.per_class_probability_json else None,
        model_version=record.model_version,
        processing_time_ms=record.processing_time_ms,
        original_image_url=record.original_image_path,
        highlighted_image_url=record.highlighted_image_path,
        stages=json.loads(record.stages_json),
        features=json.loads(record.features_json) if record.features_json else None,
    )


def _as_utc(ts):
    """SQLite returns naive datetimes. Timestamps are stored in UTC, so tag them as
    such; otherwise a browser would parse the ISO string as *local* time."""
    return ts.replace(tzinfo=datetime.timezone.utc) if ts is not None and ts.tzinfo is None else ts


def record_to_summary(r: models.Inspection) -> schemas.InspectionSummary:
    return schemas.InspectionSummary(
        id=r.id, timestamp=_as_utc(r.timestamp), original_filename=r.original_filename,
        mode=r.mode, model_mode=r.model_mode, result=r.result,
        predicted_class=r.predicted_class, model_probability=r.model_probability,
        heuristic_score=r.heuristic_score, num_regions=r.num_regions or 0,
        defect_area_percent=r.defect_area_percent, model_version=r.model_version,
        processing_time_ms=r.processing_time_ms, original_image_url=r.original_image_path,
    )


@router.post("/inspect", response_model=schemas.InspectionResponse)
async def inspect_image(
    file: UploadFile = File(...),
    mode: str = Form("demo"),
    db: Session = Depends(get_db),
):
    if mode not in ("demo", "real"):
        raise HTTPException(400, "Invalid mode. Expected 'demo' or 'real'.")

    ext = Path(file.filename).suffix.lower()
    if ext not in ALLOWED_EXTENSIONS:
        raise HTTPException(400, f"Unsupported file type '{ext}'. Allowed: {sorted(ALLOWED_EXTENSIONS)}")

    contents = await read_upload_limited(file)
    if len(contents) == 0:
        raise HTTPException(400, "Uploaded file is empty.")

    stored_name = f"{uuid.uuid4().hex[:12]}{ext}"
    with open(UPLOAD_DIR / stored_name, "wb") as f:
        f.write(contents)

    try:
        result = run_pipeline(contents, mode=mode)
    except ModelNotAvailableError as e:
        raise HTTPException(503, str(e))
    except FeatureContractError as e:
        raise HTTPException(500, str(e))
    except ValueError as e:
        # Covers corrupted/unreadable images and invalid mode from the pipeline layer
        raise HTTPException(400, f"Could not process image: {e}")
    except Exception as e:
        raise HTTPException(500, f"Pipeline processing failed: {e}")

    record = models.Inspection(
        original_filename=file.filename,
        stored_filename=stored_name,
        mode=result["mode"],
        model_mode=result["model_mode"],
        result=result["result"],
        predicted_class=result["predicted_class"],
        num_regions=result["num_regions"],
        defect_area_percent=result["defect_area_percent"],
        classifier_used=result["classifier_used"],
        model_probability=result["model_probability"],
        heuristic_score=result["heuristic_score"],
        model_version=result.get("model_version"),
        processing_time_ms=result["processing_time_ms"],
        original_image_path=result["original_image_url"],
        highlighted_image_path=result["highlighted_image_url"],
        stages_json=json.dumps(result["stages"]),
        features_json=json.dumps(result["features"]),
        per_class_probability_json=json.dumps(result["per_class_probability"]) if result.get("per_class_probability") else None,
    )
    db.add(record)
    db.commit()
    db.refresh(record)

    return _record_to_response(record)


@router.get("/inspections", response_model=list[schemas.InspectionSummary])
def list_inspections(limit: int = 50, mode: str | None = None, db: Session = Depends(get_db)):
    query = db.query(models.Inspection)
    if mode:
        query = query.filter(models.Inspection.mode == mode)
    records = query.order_by(models.Inspection.timestamp.desc()).limit(limit).all()
    return [record_to_summary(r) for r in records]


@router.get("/inspections/{inspection_id}", response_model=schemas.InspectionResponse)
def get_inspection(inspection_id: int, db: Session = Depends(get_db)):
    record = db.query(models.Inspection).filter(models.Inspection.id == inspection_id).first()
    if record is None:
        raise HTTPException(404, "Inspection not found")
    return _record_to_response(record)
